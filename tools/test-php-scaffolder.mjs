const postgresPage = buildPhpDataPage(null, {
  name: 'ledger entries', kind: 'table', columns: [
    { name: 'id', type: 'integer', notNull: false, primaryKeyOrder: 1, autoGenerated: true },
    { name: 'memo', type: 'text', notNull: false, primaryKeyOrder: 0 }
  ]
}, 'pages/ledger.php', { engine: 'postgres', tls: true });
assert.match(postgresPage, /pgsql:host=/);
assert.match(postgresPage, /sslmode=.*verify-full/);
assert.match(postgresPage, /\$sqlTable = '\"ledger entries\"'/);
assert.match(postgresPage, /SELECT "id", "memo" FROM ' \./);
assert.match(postgresPage, /PGSSLROOTCERT/);
assert.doesNotMatch(postgresPage, /DREAMCRAFT_DB_PASSWORD[^\n]*password-value/);

const accounts = { name: 'accounts', kind: 'table', columns: [
  { name: 'email', type: 'TEXT', notNull: true, primaryKeyOrder: 1 },
  { name: 'password_hash', type: 'TEXT', notNull: true, primaryKeyOrder: 0 }
] };
const auth = buildPhpAuthenticationFiles('data/site.db', accounts, { usernameColumn: 'email', passwordColumn: 'password_hash', folder: 'admin/auth', loginRedirect: 'admin/home.php', protectedPage: 'admin/home.php' });
assert.deepEqual(auth.files.map(file => file.path), ['admin/auth/session.php', 'admin/auth/login.php', 'admin/auth/require-login.php', 'admin/auth/logout.php']);
assert.match(auth.files.find(file => file.path.endsWith('/login.php')).content, /password_verify\(\$password/);
assert.match(auth.files.find(file => file.path.endsWith('/login.php')).content, /SELECT "email" AS username, "password_hash" AS password_hash FROM "accounts"/);
assert.match(auth.files.find(file => file.path.endsWith('/login.php')).content, /hash_equals\(dreamcraft_auth_csrf\(\)/);
assert.match(auth.files.find(file => file.path.endsWith('/session.php')).content, /httponly' => true, 'samesite' => 'Lax/);
assert.match(auth.files.find(file => file.path.endsWith('/require-login.php')).content, /dreamcraft_auth_logged_in/);
assert.match(auth.files.find(file => file.path.endsWith('/logout.php')).content, /REQUEST_METHOD.*POST/);
assert.equal(auth.protectedPage, 'admin/home.php');
assert.throws(() => buildPhpAuthenticationFiles('data/site.db', { ...accounts, kind: 'view' }, { usernameColumn: 'email', passwordColumn: 'password_hash' }), /requires a database table/);
assert.throws(() => buildPhpAuthenticationFiles('data/site.db', accounts, { usernameColumn: 'email', passwordColumn: 'email' }), /different text columns/);
assert.throws(() => buildPhpAuthenticationFiles('data/site.db', accounts, { usernameColumn: 'email', passwordColumn: 'password_hash', folder: '../secrets' }), /project-relative path/);
console.log('PHP data-page generation verified for SQLite, MySQL, PostgreSQL, CRUD, composite keys, escaping, environment-only secrets, and read-only views.');
