import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildPhpAuthenticationFiles, buildPhpDataPage } from '../assets/php-scaffolder.mjs';

const root = await mkdtemp(join(tmpdir(), 'dreamcraft-php-page-runtime-'));
const pagePath = join(root, 'pages', 'records.php');
const databasePath = join(root, 'data', 'site.db');
const dockerImage = 'php:8.3-cli-alpine';

function run(command, args, options = {}) {
  return execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...options });
}

try {
  await mkdir(join(root, 'pages'), { recursive: true });
  await mkdir(join(root, 'data'), { recursive: true });
  const page = buildPhpDataPage('data/site.db', {
    name: 'records', kind: 'table', columns: [
      { name: 'id', type: 'INTEGER', notNull: false, primaryKeyOrder: 1 },
      { name: 'label', type: 'TEXT', notNull: true, primaryKeyOrder: 0 },
      { name: 'active', type: 'INTEGER', notNull: true, primaryKeyOrder: 0 }
    ]
  }, 'pages/records.php');
  await writeFile(pagePath, page, 'utf8');
  const fixture = String.raw`import sqlite3, sys
connection = sqlite3.connect(sys.argv[1])
connection.execute('CREATE TABLE records (id INTEGER PRIMARY KEY, label TEXT NOT NULL, active INTEGER NOT NULL)')
connection.executemany('INSERT INTO records (id, label, active) VALUES (?, ?, ?)', [(number, f"{'Needle' if number <= 30 else 'Other'} item {number:03d}", 1) for number in range(1, 61)])
connection.execute("CREATE VIEW record_summary AS SELECT COUNT(*) AS total, 'All records' AS label FROM records")
connection.commit()
connection.close()`;
  run('python', ['-c', fixture, databasePath]);
  await writeFile(join(root, 'run.php'), String.raw`<?php
session_start();
$_SESSION['dreamcraft_csrf'] = 'runtime-test-token';
session_write_close();
$method = $argv[1] ?? 'GET';
parse_str($argv[2] ?? '', $_GET);
if ($method === 'POST') { parse_str($argv[3] ?? '', $_POST); }
$_SERVER['REQUEST_METHOD'] = $method;
$_SERVER['PHP_SELF'] = '/pages/records.php';
require $argv[4] ?? (__DIR__ . '/pages/records.php');
`, 'utf8');

  const viewPage = buildPhpDataPage('data/site.db', {
    name: 'record_summary', kind: 'view', columns: [
      { name: 'total', type: 'INTEGER', notNull: false, primaryKeyOrder: 0 },
      { name: 'label', type: 'TEXT', notNull: false, primaryKeyOrder: 0 }
    ]
  }, 'pages/summary.php');
  await writeFile(join(root, 'pages', 'summary.php'), viewPage, 'utf8');
  const passwordHash = run('docker', ['run', '--rm', '--network=none', dockerImage, 'php', '-r', 'echo password_hash("correct horse", PASSWORD_DEFAULT);']);
  run('python', ['-c', String.raw`import sqlite3, sys
db = sqlite3.connect(sys.argv[1])
db.execute('CREATE TABLE accounts (email TEXT PRIMARY KEY, password_hash TEXT NOT NULL)')
db.execute('INSERT INTO accounts VALUES (?, ?)', ('ada@example.test', sys.argv[2]))
db.commit(); db.close()`, databasePath, passwordHash]);
  const auth = buildPhpAuthenticationFiles('data/site.db', { name: 'accounts', kind: 'table', columns: [
    { name: 'email', type: 'TEXT', notNull: true, primaryKeyOrder: 1 },
    { name: 'password_hash', type: 'TEXT', notNull: true, primaryKeyOrder: 0 }
  ] }, { usernameColumn: 'email', passwordColumn: 'password_hash', folder: 'auth', loginRedirect: 'admin/home.php', protectedPage: 'admin/home.php' });
  for (const file of auth.files) {
    const absolute = join(root, ...file.path.split('/'));
    await mkdir(join(absolute, '..'), { recursive: true });
    await writeFile(absolute, file.content, 'utf8');
  }
  await mkdir(join(root, 'admin'), { recursive: true });
  await writeFile(join(root, 'admin', 'home.php'), "<?php\ndeclare(strict_types=1);\nrequire_once __DIR__ . '/../auth/require-login.php';\necho 'PRIVATE ADMIN'; echo dreamcraft_auth_logout_form();\n", 'utf8');
  const mysqlPage = buildPhpDataPage(null, {
    name: 'records', kind: 'table', columns: [
      { name: 'id', type: 'int', notNull: false, primaryKeyOrder: 1, autoGenerated: true },
      { name: 'label', type: 'varchar(200)', notNull: true, primaryKeyOrder: 0 }
    ]
  }, 'pages/mysql.php', { engine: 'mysql', tls: true });
  const postgresPage = buildPhpDataPage(null, {
    name: 'records', kind: 'table', columns: [
      { name: 'id', type: 'integer', notNull: false, primaryKeyOrder: 1, autoGenerated: true },
      { name: 'label', type: 'text', notNull: false, primaryKeyOrder: 0 }
    ]
  }, 'pages/postgres.php', { engine: 'postgres', tls: true });
  await writeFile(join(root, 'pages', 'mysql.php'), mysqlPage, 'utf8');
  await writeFile(join(root, 'pages', 'postgres.php'), postgresPage, 'utf8');

  const volume = `${root}:/work`;
  const phpArgs = (method, query = '', body = '', targetPage = '/work/pages/records.php') => [
    'run', '--rm', '--network=none', '--volume', volume, '--workdir', '/work',
    dockerImage, 'php', '/work/run.php', method, query, body, targetPage
  ];
  for (const file of ['records.php', 'summary.php', 'mysql.php', 'postgres.php']) {
    const lint = run('docker', [
      'run', '--rm', '--network=none', '--volume', volume, '--workdir', '/work',
      dockerImage, 'php', '-l', `/work/pages/${file}`
    ]);
    assert.match(lint, /No syntax errors detected/);
  }
  for (const file of ['session.php', 'login.php', 'require-login.php', 'logout.php']) {
    const lint = run('docker', ['run', '--rm', '--network=none', '--volume', volume, dockerImage, 'php', '-l', `/work/auth/${file}`]);
    assert.match(lint, /No syntax errors detected/);
  }

  const matchingSecondPage = run('docker', phpArgs('GET', 'q=needle&page=2'));
  assert.match(matchingSecondPage, /Records <small>\(30\)<\/small>/);
  assert.match(matchingSecondPage, /Page 2 of 2/);
  for (const id of [26, 27, 28, 29, 30]) assert.match(matchingSecondPage, new RegExp(`id: ${id}<\/strong>`));
  assert.doesNotMatch(matchingSecondPage, /id: 25<\/strong>|id: 31<\/strong>/);

  const firstPage = run('docker', phpArgs('GET', 'page=1'));
  assert.match(firstPage, /Records <small>\(60\)<\/small>/);
  assert.match(firstPage, /Page 1 of 3/);
  assert.match(firstPage, /id: 25<\/strong>/);
  assert.doesNotMatch(firstPage, /id: 26<\/strong>/);

  const finalPage = run('docker', phpArgs('GET', 'page=3'));
  assert.match(finalPage, /Page 3 of 3/);
  assert.match(finalPage, /id: 60<\/strong>/);
  assert.doesNotMatch(finalPage, /id: 50<\/strong>/);

  const injectionAttempt = run('docker', phpArgs('GET', 'q=%27%20OR%201%3D1%20--'));
  assert.match(injectionAttempt, /Records <small>\(0\)<\/small>/);
  assert.match(injectionAttempt, /No matching records/);

  const created = run('docker', phpArgs('POST', '', 'action=create&csrf=runtime-test-token&values%5Blabel%5D=Created+Record&values%5Bactive%5D=1'));
  assert.match(created, /Record created\./);
  assert.match(created, /Records <small>\(61\)<\/small>/);
  assert.match(run('docker', phpArgs('GET', 'q=Created')), /Created Record/);

  const updateBody = 'action=update&csrf=runtime-test-token&primary%5Bid%5D=61&values%5Blabel%5D=Updated+Record&values%5Bactive%5D=0';
  const updated = run('docker', phpArgs('POST', 'q=Updated', updateBody));
  assert.match(updated, /Record updated\./);
  assert.match(updated, /Updated Record/);
  assert.doesNotMatch(updated, /Created Record/);

  const rejectedDelete = run('docker', phpArgs('POST', '', 'action=delete&csrf=invalid&primary%5Bid%5D=61'));
  assert.match(rejectedDelete, /Invalid form token/);
  assert.match(run('docker', phpArgs('GET', '')), /Records <small>\(61\)<\/small>/);

  const deleted = run('docker', phpArgs('POST', 'q=Updated', 'action=delete&csrf=runtime-test-token&primary%5Bid%5D=61'));
  assert.match(deleted, /Record deleted\./);
  assert.match(deleted, /Records <small>\(0\)<\/small>/);
  assert.doesNotMatch(deleted, /Updated Record/);
  assert.match(run('docker', phpArgs('GET', '')), /Records <small>\(60\)<\/small>/);

  const viewOutput = run('docker', phpArgs('GET', '', '', '/work/pages/summary.php'));
  assert.match(viewOutput, /<dt>total<\/dt><dd>60<\/dd>/);
  assert.match(viewOutput, /<dt>label<\/dt><dd>All records<\/dd>/);
  assert.doesNotMatch(viewOutput, /<h2>Create record<\/h2>|<form[^>]*class="record-form"|<form[^>]*class="delete-form"/);

  const authHarness = String.raw`<?php
session_id($argv[4] ?? 'dreamcraft-auth-runtime');
$_SERVER['REQUEST_METHOD'] = $argv[1] ?? 'GET';
$_SERVER['REQUEST_URI'] = '/admin/home.php';
$_SERVER['SCRIPT_NAME'] = '/admin/home.php';
if ($_SERVER['REQUEST_METHOD'] === 'POST') { parse_str($argv[2] ?? '', $_POST); }
require $argv[3];
`;
  await writeFile(join(root, 'auth-run.php'), authHarness, 'utf8');
  await mkdir(join(root, 'sessions'), { recursive: true });
  await writeFile(join(root, 'sessions', 'sess_dreamcraft-auth-runtime'), `dreamcraft_auth_csrf|s:18:"runtime-auth-token";`);
  const authArgs = (method, body = '', script = '/work/admin/home.php', sid = 'dreamcraft-auth-runtime') => ['run', '--rm', '--network=none', '--volume', volume, '--workdir', '/work', dockerImage, 'php', '-d', 'session.save_path=/work/sessions', '/work/auth-run.php', method, body, script, sid];
  const denied = run('docker', authArgs('GET'));
  assert.doesNotMatch(denied, /PRIVATE ADMIN/);
  const csrf = 'runtime-auth-token';
  const badLogin = run('docker', authArgs('POST', 'csrf=invalid&username=ada%40example.test&password=wrong', '/work/auth/login.php'));
  assert.match(badLogin, /Invalid form token/);
  const rejected = run('docker', authArgs('POST', `csrf=${csrf}&username=ada%40example.test&password=wrong`, '/work/auth/login.php'));
  assert.match(rejected, /The username or password was not recognized/);
  const accepted = run('docker', authArgs('POST', `csrf=${csrf}&username=ada%40example.test&password=correct+horse`, '/work/auth/login.php'));
  const { readdir, readFile } = await import('node:fs/promises');
  const sessionFiles = await readdir(join(root, 'sessions'));
  const authenticatedFile = await Promise.all(sessionFiles.map(async name => [name, await readFile(join(root, 'sessions', name), 'utf8')])).then(items => items.find(([, content]) => content.includes('dreamcraft_auth_user|s:'))?.[0]);
  assert.ok(authenticatedFile, 'successful login must persist its authenticated session');
  const authenticatedSid = authenticatedFile.slice('sess_'.length);
  const allowed = run('docker', authArgs('GET', '', '/work/admin/home.php', authenticatedSid));
  assert.match(allowed, /PRIVATE ADMIN/);
  assert.match(allowed, /name="csrf"/);
  const logoutCsrf = run('docker', ['run', '--rm', '--network=none', '--volume', volume, '--workdir', '/work', dockerImage, 'php', '-d', 'session.save_path=/work/sessions', '-r', `session_id('${authenticatedSid}'); require '/work/auth/session.php'; echo dreamcraft_auth_csrf();`]);
  const logout = run('docker', authArgs('POST', `csrf=${logoutCsrf}`, '/work/auth/logout.php', authenticatedSid));
  assert.doesNotMatch(run('docker', authArgs('GET', '', '/work/admin/home.php', authenticatedSid)), /PRIVATE ADMIN/);
  console.log('Generated PHP pages passed syntax/runtime checks for SQLite/MySQL/PostgreSQL, PDO SQLite CRUD/security/search/pagination, and authentication session, CSRF, password verification, protected-page access, and logout behavior.');
} finally {
  await rm(root, { recursive: true, force: true });
}
